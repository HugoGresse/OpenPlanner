import { Capability, CAPABILITIES, CapabilityDomain, routeKey } from './capabilities'
import { CHAT_TOOLS } from './tools'

const ALL: readonly Capability[] = CAPABILITIES

export const toolNames = (type: 'read' | 'proposal'): string[] =>
    CHAT_TOOLS.filter((tool) => tool.type === type).map((tool) => tool.name)

export const toolsForCapability = (id: string): string[] =>
    CHAT_TOOLS.filter((tool) => (tool.capabilities as string[]).includes(id)).map((tool) => tool.name)

// Every `expected*` sanity-check argument of the write tools, e.g. expectedSpeakerName.
export const expectedArgNames = (): string[] => {
    const names = CHAT_TOOLS.filter((tool) => tool.type === 'proposal').flatMap((tool) =>
        Object.keys((tool.parameters as { properties?: object }).properties ?? {}).filter((key) =>
            key.startsWith('expected')
        )
    )
    return [...new Set(names)]
}

// `openplanner whatsapp status|start` for commands that share their first word.
const compactCommands = (commands: string[]): string[] => {
    const byGroup = new Map<string, string[]>()
    for (const command of commands) {
        const [group, ...rest] = command.split(' ')
        byGroup.set(group, [...(byGroup.get(group) ?? []), rest.join(' ')])
    }
    return [...byGroup.entries()].map(([group, subcommands]) =>
        [`openplanner ${group}`, subcommands.filter(Boolean).join('|')].filter(Boolean).join(' ')
    )
}

const MAX_LISTED_SUMMARIES = 3

// Capabilities the assistant cannot do, one line per (domain, reason) so related gaps read as one sentence.
// The assistant's own plumbing (chat domain) is left out.
export const assistantGapLines = (): string[] => {
    const groups = new Map<string, Capability[]>()
    for (const capability of ALL) {
        if (!capability.assistantGap || capability.domain === 'chat') continue
        const key = `${capability.domain}\u0000${capability.assistantGap}`
        groups.set(key, [...(groups.get(key) ?? []), capability])
    }
    return [...groups.values()].map((items) => {
        const what =
            items.length > MAX_LISTED_SUMMARIES
                ? `${items[0].domain} (${items.length} operations)`
                : items.map((item) => item.summary).join('; ')
        const commands = compactCommands(items.flatMap((item) => (item.cli ? [item.cli] : [])))
        const cli = commands.length > 0 ? ` CLI: ${commands.map((command) => `\`${command}\``).join(', ')}.` : ''
        return `- ${what}: ${items[0].assistantGap}${cli}`
    })
}

const DOMAIN_ORDER: CapabilityDomain[] = [...new Set(ALL.map((capability) => capability.domain))]

const cell = (value: string | null | undefined) => value || '—'

// Markdown table embedded in the CLI skill (between the capability markers) and the PR description.
export const renderCapabilityMatrix = (): string => {
    const rows = DOMAIN_ORDER.flatMap((domain) =>
        ALL.filter((capability) => capability.domain === domain).map((capability) => {
            const tools = toolsForCapability(capability.id)
            const assistant = tools.length > 0 ? tools.map((name) => `\`${name}\``).join(', ') : 'not available'
            return `| ${domain} | ${capability.summary} | ${cell(
                capability.route && `\`${routeKey(capability.route)}\``
            )} | ${cell(capability.cli && `\`${capability.cli}\``)} | ${assistant} |`
        })
    )
    return [
        '| Area | Capability | REST route | CLI | Assistant (web chat, Slack, MCP) |',
        '| --- | --- | --- | --- | --- |',
        ...rows,
    ].join('\n')
}

export const CAPABILITY_MARKERS = {
    start: '<!-- capabilities:start (generated by `npm run capabilities:docs` in functions/, do not edit) -->',
    end: '<!-- capabilities:end -->',
} as const

// Gaps of the API itself: no REST route, so no CLI command (the assistant may still read it with its tools).
export const renderApiGaps = (): string =>
    ALL.filter((capability) => !capability.route)
        .map((capability) => {
            const tools = toolsForCapability(capability.id)
            const where =
                tools.length > 0 ? `the assistant (\`${tools.join('`, `')}\`) and the web admin` : 'web admin only'
            return `- ${capability.summary} (${capability.domain}): no API route; ${where}.`
        })
        .join('\n')

// Block embedded in SKILL.md: both gap lists, the assistant one being the exact text of its system prompt.
export const renderSkillBlock = (): string =>
    [
        CAPABILITY_MARKERS.start,
        '',
        '### Not available yet',
        '',
        renderApiGaps(),
        '',
        '### Not available in the assistant',
        '',
        assistantGapLines().join('\n'),
        '',
        'Every capability per surface (REST route, CLI command, assistant tool): [capabilities.md](capabilities.md).',
        '',
        CAPABILITY_MARKERS.end,
    ].join('\n')

export const renderCapabilitiesDoc = (): string =>
    [
        '# OpenPlanner capabilities',
        '',
        '<!-- Generated by `npm run capabilities:docs` in functions/ from functions/src/api/routes/chat/capabilities/, do not edit. -->',
        '',
        'Assistant = the in-app chat, the Slack bot and `openplanner chat` (one agent). Its writes are proposals a human applies; the "not available" rows are listed in its system prompt so it says so instead of improvising. The MCP endpoint (`POST /v1/{eventId}/mcp`) serves the same tools to external AI clients, plus `applyProposal` to apply a proposal.',
        '',
        renderCapabilityMatrix(),
        '',
    ].join('\n')

export const replaceCapabilityBlock = (document: string): string => {
    const start = document.indexOf(CAPABILITY_MARKERS.start)
    const end = document.indexOf(CAPABILITY_MARKERS.end)
    if (start === -1 || end === -1) throw new Error('Capability markers not found')
    return document.slice(0, start) + renderSkillBlock() + document.slice(end + CAPABILITY_MARKERS.end.length)
}
